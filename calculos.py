
def calcular(escolha, val1, val2):
    if escolha == 1:
        resultado = (val1 + val2)
        print(f"O seu resultado foi {resultado}")
    elif escolha == 2:
        resultado = (val1 - val2)
        print(f"O seu resultado foi {resultado}")
    elif escolha == 3:
        resultado = (val1 * val2)
        print(f"O seu resultado foi {resultado}")
    elif escolha == 4:
        resultado = (val1 / val2)
        print(f"O seu resultado foi {resultado}")
